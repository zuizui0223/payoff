"""Pure synthetic guardrails; original bird/radar outcomes are never test fixtures."""
from __future__ import annotations
import pytest
pytest.importorskip("numpy", reason="NumPy only needed in empirical extras")
from scripts import payoff_b_radar_greenup_heldout as p


def rows():
    data=[]
    for i in range(8):
        for k in range(7):
            temp=4+0.35*i + 0.06*k*k + 0.3*((i*k)%3)
            green=125+2*i - 0.2*k + (((i+2)*k)%9)*3
            year=2003+k
            y=100+i*2 + 0.12*k + 1.4*temp+0.65*green
            data.append({
              "site":f"S{i}","year":year,
              "spring_q50":y, "spring_mean_temp":temp,
              "mean_greenup":green,
            })
    return data


def contract():
    return {
      "date":"2026-11-22","status":"TEST",
      "support_before_any_new_effect":{
        "min_complete_pairs":30,"min_stations":5,"min_years":5,
        "min_site_years_per_heldout_year":5,"max_missing_focal_fraction":0.2,
        "min_residual_df":10,
        "min_greenup_after_station_year_trend_temp_rms_days":0.1,
        "max_greenup_partial_vif":100,
      },
      "uncertainty":{"replicates":100,"seed":42}
    }


def test_synthetic_tracked_site_years_have_support():
    z=p.check_design(rows(),contract())
    assert z["status"]=="PASS"
    assert z["n_years"]==7
    assert z["n_sites"]==8


def test_original_numeric_source_gate_no_effect_from_missing_y():
    d=rows()
    d[0]["spring_q50"]=None
    x=p.check_design(d,contract())
    assert x["n_missing"]==1
    assert x["n_complete"]==55


def test_duplicate_original_keys_rejected(tmp_path):
    file=tmp_path/"private.csv"
    file.write_text("site,year,spring_q50,spring_mean_temp,mean_greenup\nA,2003,99,4,110\nA,2003,100,5,111\n")
    with pytest.raises(ValueError,match="Duplicate"):
        p.source_rows(file)


def test_no_phenology_variation_blocks_fit_without_looking_at_y():
    d=rows()
    for x in d:
        x["mean_greenup"]=50+x["spring_mean_temp"]*3
    assert p.check_design(d,contract())["status"]=="NOT_ESTIMABLE"


def test_synthetic_full_holdout_math_can_be_calculated():
    x=p.estimate(rows(),contract())
    assert x["prefit"]["status"]=="PASS"
    assert x["ecological_effect"]["n_heldout_years"]==7
    # Response was generated by greenup, so this checks the implementation only.
    assert x["ecological_effect"]["primary_heldout_equal_year_mean_mse_gain"]>0
    assert x["new_animal_info_mechanism_identified"] is False


def test_schema_exposes_only_approved_original_fields():
    assert p.DATA_COLS==("site","year","spring_q50","spring_mean_temp","mean_greenup")
    assert "ebird" not in str(p.DATA_COLS).lower()
